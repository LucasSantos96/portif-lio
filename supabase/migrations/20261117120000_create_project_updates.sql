-- Linha do tempo por projeto: cada atualização relevante com data, texto em PT/EN
-- e imagens opcionais. Aditiva: não altera portfolio_projects.
create table if not exists public.project_updates (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.portfolio_projects (id) on delete cascade,
  slug text not null,
  occurred_at date not null,
  title text not null,
  title_en text,
  description text not null,
  description_en text,
  images text[] not null default '{}',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (project_id, slug)
);

create index if not exists project_updates_project_id_occurred_at_idx
  on public.project_updates (project_id, occurred_at desc);

-- Só o servidor (conexão direta do Prisma) acessa a tabela.
alter table public.project_updates enable row level security;
