-- Tabelas de participantes e progresso do Roadmap AI Engineer 2027.

create table if not exists public.roadmap_participants (
  id bigint generated by default as identity primary key,
  token text not null unique,
  name text not null,
  email text not null unique,
  locale text not null default 'pt',
  created_at timestamptz not null default now(),
  last_active_at timestamptz not null default now()
);

create index if not exists roadmap_participants_last_active_idx
  on public.roadmap_participants (last_active_at desc);

create table if not exists public.roadmap_completions (
  id bigint generated by default as identity primary key,
  participant_id bigint not null references public.roadmap_participants (id) on delete cascade,
  node_id text not null,
  completed_at timestamptz not null default now(),
  unique (participant_id, node_id)
);

create index if not exists roadmap_completions_participant_idx
  on public.roadmap_completions (participant_id);
