-- Artigos do blog. Cada artigo existe em português e em inglês, com slug próprio
-- por idioma (URLs /blog/<slug> e /en/blog/<slug_en>).
create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  slug_en text not null unique,
  title text not null,
  title_en text not null,
  excerpt text not null,
  excerpt_en text not null,
  body text not null,
  body_en text not null,
  cover_url text,
  cover_alt text,
  cover_alt_en text,
  tags text[] not null default '{}',
  tags_en text[] not null default '{}',
  published boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists articles_published_at_idx
  on public.articles (published, published_at desc);

-- Só o servidor (service role / conexão direta) acessa a tabela; a API pública
-- do Supabase não deve expor rascunhos.
alter table public.articles enable row level security;
